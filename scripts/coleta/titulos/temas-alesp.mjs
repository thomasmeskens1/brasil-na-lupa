const escapar = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
/** Regra pública (fonte alesp-indexador) para um tema: lista exata de termos do tesauro. */
export function regraAlesp(tema) {
  return { fonte: 'alesp-indexador', padrao: `^(${TERMOS_ALESP[tema].map(escapar).join('|')})$`, tema };
}
